const assert = require("assert/strict");
const fs = require("fs");
const path = require("path");
const source = fs.readFileSync(path.resolve(__dirname, "../../.github/workflows/generate-content.yml"), "utf8");
assert(source.includes("workflow_dispatch:"));
assert(!/^  (push|pull_request|schedule):/m.test(source), "Paid generation must never start from a commit or schedule.");
assert(/contents: read/.test(source) && !/contents: write/.test(source));
assert(/allow_paid_generation:[\s\S]*?type: boolean\s+default: false/.test(source));
assert(source.includes("inputs.allow_paid_generation && inputs.approved_revision == github.sha && vars.PAID_CONTENT_APPROVAL_CONFIGURED == 'true'"));
assert(source.includes("environment: paid-content-generation"));
assert(source.includes("persist-credentials: false"));
assert(source.includes("ref: ${{ inputs.approved_revision }}"));
const runs = [...source.matchAll(/^[ \t]+(?:-[ \t]+)?run:[ \t]*(\S[^\r\n]*)/gm)].map(m => m[1].trim());
assert.deepEqual(runs, ["npm run content:generate", "npm run content:validate"], "No publication, push, webhook or arbitrary shell path may enter the paid draft job.");
const actions = [...source.matchAll(/uses:\s*(\S+)/g)].map(m => m[1]);
assert.deepEqual(actions, ["actions/checkout@v4", "actions/setup-node@v4", "actions/upload-artifact@v4"]);
assert(!/content:(auto-publish|publish)|git\s+push|NOTIFICATION_WEBHOOK_URL|NETLIFY_BUILD_HOOK_URL/.test(source));
assert(source.includes("health-article-draft-awaiting-medical-review"));
console.log("Article workflow safety checks passed: manual opt-in, revision/environment gate, read token and draft-only commands.");
